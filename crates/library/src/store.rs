    /// The entry that is playing now, if the active playlist names one.
    pub fn current(&self) -> Result<Option<QueueEntry>, Error> {
        self.db
            .with_connection(|connection| {
                let table = active_table(connection)?;
                current_in(connection, &table)
            })
            .map_err(Error::from)
    }

    /// Appends an entry and returns it.
    ///
    /// The first entry of an empty queue becomes the current one, so a queue
    /// that is built one video at a time never loses track of what plays.
    pub fn push(
        &self,
        url: impl Into<String>,
        title: impl Into<String>,
        thumbnail: Option<&str>,
        thumbnail_url: Option<&str>,
        uploader: Option<&str>,
    ) -> Result<QueueEntry, Error> {
        let url = url.into();
        let title = title.into();
        let thumbnail = thumbnail.map(str::to_string);
        let thumbnail_url = thumbnail_url.map(str::to_string);
        let uploader = uploader.map(str::to_string);
        let id_hash = video_id_hash(&url);
        self.db
            .with_connection(|connection| {
                let table = active_table(connection)?;
                let count: i64 =
                    connection.query_row(&format!("SELECT COUNT(*) FROM {table}"), [], |row| {
                        row.get(0)
                    })?;
                let position: i64 = connection.query_row(
                    &format!("SELECT COALESCE(MAX(position), -1) + 1 FROM {table}"),
                    [],
                    |row| row.get(0),
                )?;
                let mut entry = QueueEntry {
                    id: 0,
                    position,
                    url: url.clone(),
                    title,
                    thumbnail,
                    thumbnail_url,
                    uploader,
                    id_hash: id_hash.clone(),
                    current: count == 0,
                    resolved_source: None,
                    resolved_at: None,
                    selected_video: None,
                    selected_audio: None,
                    selected_muxed: None,
                };
                insert_entry(connection, &table, &entry)?;
                entry.id = connection.last_insert_rowid();
                touch_current(connection, &table)?;
                Ok(entry)
            })
            .map_err(Error::from)
    }

    /// Inserts an entry right after the one playing now, or appends it when
    /// nothing is current yet.
    pub fn push_next(
        &self,
        url: impl Into<String>,
        title: impl Into<String>,
        thumbnail: Option<&str>,
        thumbnail_url: Option<&str>,
        uploader: Option<&str>,
    ) -> Result<QueueEntry, Error> {
        let url = url.into();
        let title = title.into();
        let thumbnail = thumbnail.map(str::to_string);
        let thumbnail_url = thumbnail_url.map(str::to_string);
        let uploader = uploader.map(str::to_string);
        let id_hash = video_id_hash(&url);
        self.db
            .with_connection(|connection| {
                let table = active_table(connection)?;
                let count: i64 =
                    connection.query_row(&format!("SELECT COUNT(*) FROM {table}"), [], |row| {
                        row.get(0)
                    })?;
                let current_position: Option<i64> = connection
                    .query_row(
                        &format!(
                            "SELECT position FROM {table} WHERE current = 1 ORDER BY position LIMIT 1"
                        ),
                        [],
                        |row| row.get(0),
                    )
                    .optional()?;
                let position: i64 = match current_position {
                    Some(position) => {
                        connection.execute(
                            &format!(
                                "UPDATE {table} SET position = position + 1 WHERE position > ?1"
                            ),
                            params![position],
                        )?;
                        position + 1
                    }
                    None => connection.query_row(
                        &format!("SELECT COALESCE(MAX(position), -1) + 1 FROM {table}"),
                        [],
                        |row| row.get(0),
                    )?,
                };

                let mut entry = QueueEntry {
                    id: 0,
                    position,
                    url: url.clone(),
                    title,
                    thumbnail,
                    thumbnail_url,
                    uploader,
                    id_hash: id_hash.clone(),
                    current: count == 0,
                    resolved_source: None,
                    resolved_at: None,
                    selected_video: None,
                    selected_audio: None,
                    selected_muxed: None,
                };
                insert_entry(connection, &table, &entry)?;
                entry.id = connection.last_insert_rowid();
                touch_current(connection, &table)?;
                Ok(entry)
            })
            .map_err(Error::from)
    }

    /// Replaces the whole queue with a single, current entry.
    ///
    /// This is what "play now" does: the old queue is dropped and the new
    /// media becomes the only thing that plays.
    pub fn replace_with(
        &self,
        url: impl Into<String>,
        title: impl Into<String>,
        thumbnail: Option<&str>,
        thumbnail_url: Option<&str>,
        uploader: Option<&str>,
    ) -> Result<QueueEntry, Error> {
        let url = url.into();
        let title = title.into();
        let thumbnail = thumbnail.map(str::to_string);
        let thumbnail_url = thumbnail_url.map(str::to_string);
        let uploader = uploader.map(str::to_string);
        let id_hash = video_id_hash(&url);
        self.db
            .with_connection(|connection| {
                let table = active_table(connection)?;
                connection.execute(&format!("DELETE FROM {table}"), [])?;
                let mut entry = QueueEntry {
                    id: 0,
                    position: 0,
                    url: url.clone(),
                    title,
                    thumbnail,
                    thumbnail_url,
                    uploader,
                    id_hash: id_hash.clone(),
                    current: true,
                    resolved_source: None,
                    resolved_at: None,
                    selected_video: None,
                    selected_audio: None,
                    selected_muxed: None,
                };
                insert_entry(connection, &table, &entry)?;
                entry.id = connection.last_insert_rowid();
                touch_current(connection, &table)?;
                Ok(entry)
            })
            .map_err(Error::from)
    }

    /// Moves the current mark to the next entry and returns it.
    ///
    /// When no entry is current yet the first one becomes current, so a queue
    /// that was filled without playing anything still starts at its head.
    /// When the last entry was current, the mark is cleared and `None` is
    /// returned: the queue has been played to its end.
    pub fn advance(&self) -> Result<Option<QueueEntry>, Error> {
        self.db
            .with_connection(|connection| {
                let table = active_table(connection)?;
                let current: Option<(i64, i64)> = connection
                    .query_row(
                        &format!(
                            "SELECT id, position FROM {table} WHERE current = 1 ORDER BY position LIMIT 1"
                        ),
                        [],
                        |row| Ok((row.get::<_, i64>(0)?, row.get::<_, i64>(1)?)),
                    )
                    .optional()?;

                let Some((_current_id, current_position)) = current else {
                    let first: Option<i64> = connection
                        .query_row(
                            &format!("SELECT id FROM {table} ORDER BY position LIMIT 1"),
                            [],
                            |row| row.get(0),
                        )
                        .optional()?;
                    let Some(first) = first else {
                        return Ok(None);
                    };
                    connection.execute(
                        &format!("UPDATE {table} SET current = 1 WHERE id = ?1"),
                        params![first],
                    )?;
                    touch_current(connection, &table)?;
                    return current_in(connection, &table);
                };

                let next: Option<i64> = connection
                    .query_row(
                        &format!(
                            "SELECT id FROM {table} WHERE position > ?1 ORDER BY position LIMIT 1"
                        ),
                        params![current_position],
                        |row| row.get(0),
                    )
                    .optional()?;

                connection.execute(&format!("UPDATE {table} SET current = 0"), [])?;
                let Some(next) = next else {
                    touch_current(connection, &table)?;
                    return Ok(None);
                };
                connection.execute(
                    &format!("UPDATE {table} SET current = 1 WHERE id = ?1"),
                    params![next],
                )?;
                touch_current(connection, &table)?;
                current_in(connection, &table)
            })
            .map_err(Error::from)
    }

    /// Moves the current mark to the entry with `id`.
    ///
    /// This is what a click in the queue list uses to continue from another
    /// entry. The entry is identified by its stable database id, so reordering
    /// the queue never loses track of what plays. An id that is not in the
    /// queue leaves the mark untouched.
    pub fn set_current(&self, id: i64) -> Result<(), Error> {
        self.db
            .with_connection(|connection| {
                let table = active_table(connection)?;
                let exists: Option<i64> = connection
                    .query_row(
                        &format!("SELECT id FROM {table} WHERE id = ?1"),
                        params![id],
                        |row| row.get(0),
                    )
                    .optional()?;
                if exists.is_some() {
                    connection.execute(&format!("UPDATE {table} SET current = 0"), [])?;
                    connection.execute(
                        &format!("UPDATE {table} SET current = 1 WHERE id = ?1"),
                        params![id],
                    )?;
                    touch_current(connection, &table)?;
                }
                Ok(())
            })
            .map_err(Error::from)
    }

